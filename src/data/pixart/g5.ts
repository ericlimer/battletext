/** Overwrite pixels: each edit is [x, y, string] written left to right from (x, y). */
const put = (px: string[], ...edits: [number, number, string][]): string[] => {
  const r = px.map((s) => [...s]);
  for (const [x, y, s] of edits) [...s].forEach((c, i) => { r[y][x + i] = c; });
  return r.map((a) => a.join(''));
};

