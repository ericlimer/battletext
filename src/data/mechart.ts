// Hand-drawn ASCII portraits of each chassis, front view (the 'Mech's right side is on the viewer's left).
// Each portrait carries a zone spec so cells can be coloured by the armour state of the location they show:
//   head  — rows from the top that belong to the head (within the torso columns)
//   legs  — first row of the legs
//   arms  — [a, b]: columns left of a are the right arm, columns at or right of b are the left arm
// Variants of one chassis share a portrait.

export interface MechArt { rows: string[]; head: number; legs: number; arms: [number, number] }

const A = (s: string, head: number, legs: number, arms: [number, number]): MechArt => {
  const rows = s.replace(/^\n/, '').replace(/\n\s*$/, '').split('\n');
  return { rows, head, legs, arms };
};

